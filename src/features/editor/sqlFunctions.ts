const BY_DIALECT: Record<SqlDialect, readonly string[]> = {
  postgres: POSTGRES,
  mysql: MYSQL,
  sqlite: SQLITE,
};

const cache = new Map<SqlDialect, readonly string[]>();

/** The dialect's built-in function names, lower case, sorted, without duplicates. */
export function builtinFunctions(dialect: SqlDialect): readonly string[] {
  let list = cache.get(dialect);
  if (!list) {
    list = [...new Set([...COMMON, ...BY_DIALECT[dialect]])].sort();
    cache.set(dialect, list);
  }
  return list;
}
