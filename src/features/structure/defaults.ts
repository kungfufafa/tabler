import type { Dialect } from "@/lib/ipc";
import { quoteString } from "@/lib/sql/quote";

/**
 * The `column_default` dropdown (TablePlus): MySQL offers EMPTY, NULL, AUTO_INCREMENT,
 * CURRENT_TIMESTAMP, NOW() and "Advanced…" (free text); PostgreSQL the kinds Sequence (an
 * identity), Expression and Constant. A preset turns into a column edit.
 */
export type DefaultPreset =
  /** Sets the default to this SQL expression (null = no default). */
  | { kind: "set"; label: string; expr: string | null; hint?: string }
  /** Auto increment on (MySQL AUTO_INCREMENT, PostgreSQL identity). */
  | { kind: "autoIncrement"; label: string; hint?: string }
  /** Asks for an expression (free text, inserted as written). */
  | { kind: "expression"; label: string; hint?: string }
  /** Asks for a constant value, quoted as a literal unless numeric / boolean. */
  | { kind: "constant"; label: string; hint?: string };

export function defaultPresets(dialect: Dialect, dataType: string): DefaultPreset[] {
  if (dialect === "mysql")
    return [
      { kind: "set", label: "EMPTY", expr: "''", hint: "empty string" },
      { kind: "set", label: "NULL", expr: null, hint: "no default" },
      { kind: "autoIncrement", label: "AUTO_INCREMENT" },
      { kind: "set", label: "CURRENT_TIMESTAMP", expr: "CURRENT_TIMESTAMP" },
      { kind: "set", label: "NOW()", expr: "NOW()" },
      { kind: "expression", label: "Advanced…", hint: "type the default" },
    ];
  if (dialect === "postgres") {
    const presets: DefaultPreset[] = [
      { kind: "autoIncrement", label: "Sequence", hint: "identity (GENERATED BY DEFAULT)" },
      { kind: "expression", label: "Expression…", hint: "now(), gen_random_uuid() …" },
      { kind: "constant", label: "Constant…", hint: "a literal value" },
      { kind: "set", label: "No default", expr: null },
    ];
    if (/^(timestamp|date|time)/i.test(dataType.trim()))
      presets.splice(1, 0, { kind: "set", label: "now()", expr: "now()" });
    if (/^uuid$/i.test(dataType.trim()))
      presets.splice(1, 0, { kind: "set", label: "gen_random_uuid()", expr: "gen_random_uuid()" });
    return presets;
  }
  return [
    { kind: "set", label: "NULL", expr: null, hint: "no default" },
    { kind: "set", label: "CURRENT_TIMESTAMP", expr: "CURRENT_TIMESTAMP" },
    { kind: "set", label: "CURRENT_DATE", expr: "CURRENT_DATE" },
    { kind: "expression", label: "Advanced…", hint: "type the default" },
  ];
}

const NUMERIC_TYPE =
  /^(tiny|small|medium|big)?int(eger)?\b|^int[248]$|^(numeric|decimal|dec|real|float|double|money)\b|^serial|^bigserial|^smallserial/i;

/**
 * A constant typed in the "Constant…" field as SQL: numbers stay bare for numeric columns,
 * true / false for booleans, NULL as is; anything else becomes a quoted string literal.
 */
export function constantDefault(dialect: Dialect, dataType: string, raw: string): string {
  const v = raw.trim();
  if (/^null$/i.test(v)) return "NULL";
  if (NUMERIC_TYPE.test(dataType.trim()) && /^[+-]?(\d+(\.\d*)?|\.\d+)(e[+-]?\d+)?$/i.test(v))
    return v;
  if (/^bool/i.test(dataType.trim()) && /^(true|false)$/i.test(v)) return v.toLowerCase();
  return quoteString(dialect, raw);
}

/** What kind of default an expression is, for the PostgreSQL cell's badge. */
export function defaultKind(expr: string | null): "sequence" | "expression" | "constant" | null {
  if (expr === null) return null;
  const e = expr.trim();
  if (/^nextval\(/i.test(e)) return "sequence";
  if (/^('(?:[^']|'')*'|[+-]?\d+(\.\d+)?|true|false|null)(::[\w ]+(\[\])?)?$/i.test(e))
    return "constant";
  return "expression";
}
