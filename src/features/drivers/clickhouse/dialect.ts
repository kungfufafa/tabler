/** `` `name` `` with backslash and backquote escaped, as `spec::backticked_backslash` quotes. */
export const backticked = (name: string): string =>
  `\`${name.replaceAll("\\", "\\\\").replaceAll("`", "\\`")}\``;

/** CodeMirror's dialect (types: the bare names of `CLICKHOUSE_COLUMN_TYPES`). */
export const CLICKHOUSE_SQL = SQLDialect.define({
  keywords: KEYWORDS,
  builtin: CLICKHOUSE_FUNCTIONS.join(" "),
  types: [...new Set(CLICKHOUSE_COLUMN_TYPES.map((t) => t.replace(/\(.*$/, "")))].join(" "),
  identifierQuotes: '`"',
  backslashEscapes: true,
  hashComments: true,
  slashComments: true,
  doubleDollarQuotedStrings: true,
  // Names keep their case: `Events` and `events` are two tables.
  caseInsensitiveIdentifiers: false,
});

export const clickhouseSqlUi: DialectUi = {
  label: "ClickHouse SQL",
  codemirror: () => CLICKHOUSE_SQL,
  // sql-formatter has a `clickhouse` language, but the caps do not grant Format (the backend's
  // brief: not tested yet), so the button stays hidden and nothing would call it.
  formatter: null,
  functions: CLICKHOUSE_FUNCTIONS,
  columnTypes: CLICKHOUSE_COLUMN_TYPES,
  quoteIdent: backticked,
};
