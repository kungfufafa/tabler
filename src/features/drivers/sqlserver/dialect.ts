/** `[name]` with `]` doubled, as `sqlgen::dialect::tsql` quotes. */
export const bracketed = (name: string): string => `[${name.replaceAll("]", "]]")}]`;

export const tsqlUi: DialectUi = {
  label: "T-SQL",
  codemirror: () => MSSQL,
  // Not sql-formatter's `transactsql`: it joins a `GO 3` line with the next statement and puts a
  // column named `go` on a line of its own, a batch separator. The caps do not grant Format either.
  formatter: null,
  functions: TSQL_FUNCTIONS,
  columnTypes: TSQL_COLUMN_TYPES,
  quoteIdent: bracketed,
};
