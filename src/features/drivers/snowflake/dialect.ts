/**
 * Snowflake SQL in the editor: double-quoted names, `'…'` strings with backslash escapes, untagged
 * `$$…$$` bodies, `--` and `//` comments, Snowflake's words and the names completion offers, and
 * sql-formatter's `snowflake` language for Format (the session's caps grant it). Splitting
 * (`$$` bodies and Snowflake Scripting blocks kept whole) and Safe Mode come from the backend's
 * lexer profile (`bindings/lex/snowflake.json`); Safe Mode also reads a quoted `"NEXTVAL"` as a
 * write, as the backend does (`classify.ts`).
 */

/** Statement and clause words beyond standard SQL's (lower case, as CodeMirror takes them). */
const KEYWORDS = [
  "ilike rlike qualify lateral flatten pivot unpivot sample tablesample match_recognize",
  "connect by prior start changes at before stream offset timestamp statement",
  "show describe desc explain using text json tabular use warehouse role database schema",
  "transient temporary temp volatile secure recursive materialized dynamic iceberg hybrid",
  "external stage pipe task alert sequence file format integration share masking policy",
  "tag clone undrop swap cluster copy grants managed access comment unset session",
  "put get list ls remove rm begin transaction commit rollback call procedure function",
  "returns language javascript python java scala sql handler runtime_version packages",
  "imports execute immediate declare let cursor resultset exception return loop for while",
  "repeat until break continue if elseif then case end default nulls first last",
  "merge matched qualify limit fetch next only top",
].join(" ");

/** Snowflake's type words beyond standard SQL's. */
const TYPES = [
  "number decimal numeric int integer bigint smallint tinyint byteint float float4 float8",
  "double real varchar char character string text binary varbinary boolean date datetime",
  "time timestamp timestamp_ltz timestamp_ntz timestamp_tz variant object array map",
  "geography geometry vector file",
].join(" ");

/** CodeMirror's dialect: standard SQL's, with Snowflake's lexing and words. */
export const SNOWFLAKE_SQL = SQLDialect.define({
  ...StandardSQL.spec,
  keywords: `${StandardSQL.spec.keywords ?? ""} ${KEYWORDS}`,
  types: `${StandardSQL.spec.types ?? ""} ${TYPES}`,
  identifierQuotes: '"',
  backslashEscapes: true,
  doubleDollarQuotedStrings: true,
  slashComments: true,
  // Unquoted names fold to upper case: `orders` and `ORDERS` are one table.
  caseInsensitiveIdentifiers: true,
});

