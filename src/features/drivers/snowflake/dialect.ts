/**
 * `"name"` with `"` doubled, as `sqlgen::dialect::snowflake` quotes: the exact stored case, so
 * a name SHOW returned in lower case stays lower case.
 */
export const doubleQuoted = (name: string): string => `"${name.replaceAll('"', '""')}"`;

