//! DDL operation types (M5): what the table designer sends, the plan it previews, and the result
//! of applying it. Generation lives in `sqlgen::ddl`.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::error::ErrorPayload;
use crate::types::schema::TableRef;

/// A column as the designer describes it. `data_type` is dialect SQL (`varchar(255)`,
/// `bigint`, `TEXT`); `default_expr` is raw SQL inserted verbatim (`0`, `'n/a'`, `now()`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct ColumnDef {
    pub name: String,
    pub data_type: String,
    pub nullable: bool,
    pub default_expr: Option<String>,
    /// PG: `GENERATED BY DEFAULT AS IDENTITY`; MySQL: `AUTO_INCREMENT`; SQLite: `AUTOINCREMENT`
    /// on an `INTEGER PRIMARY KEY`.
    pub auto_increment: bool,
    pub comment: Option<String>,
    pub collation: Option<String>,
    /// MySQL only (`UNSIGNED`); ignored elsewhere with a warning.
    pub unsigned: bool,
}

/// An index to create. Entries of `columns` are column names (quoted by the generator) unless
/// they contain spaces or parentheses, in which case they are inserted verbatim (`lower(email)`,
/// `created_at DESC`, MySQL `name(10)`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct IndexDef {
    pub name: String,
    pub columns: Vec<String>,
    pub unique: bool,
    /// PG `USING <method>` / MySQL `USING BTREE|HASH`; ignored on SQLite.
    pub method: Option<String>,
    /// Partial-index predicate (PG, SQLite); ignored on MySQL with a warning.
    pub predicate: Option<String>,
}

/// A foreign key to add. `name` is optional: the server picks one when it is `None`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct FkDef {
    pub name: Option<String>,
    pub columns: Vec<String>,
    pub ref_table: TableRef,
    pub ref_columns: Vec<String>,
    /// `CASCADE`, `SET NULL`, `SET DEFAULT`, `RESTRICT`, `NO ACTION`.
    pub on_update: Option<String>,
    pub on_delete: Option<String>,
}

/// One schema change. Every table-scoped op carries its target so a plan can touch several
/// tables; SQLite rebuilds fold all structural ops on the planned table into one rebuild.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "op", rename_all = "camelCase", rename_all_fields = "camelCase")]
#[ts(export)]
pub enum DdlOp {
    CreateTable {
        table: TableRef,
        columns: Vec<ColumnDef>,
        primary_key: Vec<String>,
        if_not_exists: bool,
    },
    DropTable {
        table: TableRef,
        if_exists: bool,
        cascade: bool,
    },
    TruncateTable {
        table: TableRef,
        restart_identity: bool,
        cascade: bool,
    },
    RenameTable {
        table: TableRef,
        new_name: String,
    },
    AddColumn {
        table: TableRef,
        column: ColumnDef,
        /// MySQL: `AFTER <col>`; an empty string means `FIRST`. Warned and ignored elsewhere.
        after: Option<String>,
    },
    DropColumn {
        table: TableRef,
        name: String,
    },
    RenameColumn {
        table: TableRef,
        name: String,
        new_name: String,
    },
    AlterColumnType {
        table: TableRef,
        name: String,
        new_type: String,
        /// PG `USING <expr>` conversion; ignored elsewhere with a warning.
        using: Option<String>,
    },
    AlterColumnNullable {
        table: TableRef,
        name: String,
        nullable: bool,
    },
    AlterColumnDefault {
        table: TableRef,
        name: String,
        /// `None` drops the default.
        default_expr: Option<String>,
    },
    SetColumnComment {
        table: TableRef,
        name: String,
        comment: Option<String>,
    },
    SetTableComment {
        table: TableRef,
        comment: Option<String>,
    },
    AddIndex {
        table: TableRef,
        index: IndexDef,
    },
    DropIndex {
        table: TableRef,
        name: String,
    },
    AddForeignKey {
        table: TableRef,
        fk: FkDef,
    },
    DropForeignKey {
        table: TableRef,
        name: String,
    },
    AddPrimaryKey {
        table: TableRef,
        columns: Vec<String>,
    },
    DropPrimaryKey {
        table: TableRef,
    },
    RawSql {
        sql: String,
    },
}

/// Statements to run, in order, plus what the generator could not express faithfully.
/// `transactional` is false for MySQL (DDL auto-commits) and for SQLite rebuilds (the plan
/// carries its own `BEGIN`/`COMMIT` because `PRAGMA foreign_keys` must run outside them).
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct DdlPlan {
    pub statements: Vec<String>,
    pub warnings: Vec<String>,
    pub transactional: bool,
}

/// Outcome of `apply_ddl`. A failed transactional plan has an empty `executed` (rolled back);
/// a failed sequential plan lists the statements that did commit before `failed_index`.
#[derive(Debug, Clone, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct DdlResult {
    pub executed: Vec<String>,
    pub failed_index: Option<usize>,
    pub error: Option<ErrorPayload>,
    pub duration_ms: u64,
}
